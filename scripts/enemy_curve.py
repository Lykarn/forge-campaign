"""Give each region the enemies that fit its place in the campaign, from measured strength.

Adventure's colour regions all roam enemies of about the same strength (region_bench.py: 15-35%
enemy wins everywhere), so the campaign had no difficulty curve. This takes a full benchmark of
the enemies (bench.py --grunts -1 --elites -1 --bosses 0), scores each enemy by its win rate,
and writes plane/world/biomes/<biome>.patch.json with a new "enemies" list per region:

  - candidates: the biome's own enemies, plus any non-boss enemy whose deck colours fit the
    region (so the list keeps its colour identity);
  - band: a strength band by the region's step in the campaign (STEP below): weakest in the
    hub and the first region, strongest in the last two;
  - at least MIN_ENEMIES per region, topped up with the nearest strengths if the band is thin.

Usage: python scripts/enemy_curve.py [results.csv]   (default: the newest full run)
"""
from __future__ import annotations

import csv
import json
import re
import sys
from collections import defaultdict
from pathlib import Path

from common import FORGE, OUT, ROOT

COMMON = FORGE / "forge-gui" / "res" / "adventure" / "common" / "world"
# Each region's step in the campaign, and the strength band (percentiles of all enemies) it roams.
STEP = {"hub": (0.0, 0.45), "white": (0.1, 0.55), "blue": (0.3, 0.75), "green": (0.3, 0.75),
        "red": (0.5, 1.0), "black": (0.5, 1.0)}
COLOURS = {"hub": "", "white": "W", "blue": "U", "green": "G", "red": "R", "black": "B"}
MIN_ENEMIES = 18


def biome_files() -> dict[str, Path]:
    out = {}
    for f in (COMMON / "biomes").glob("*.json"):
        try:
            out[json.loads(re.sub(r",\s*([\]}])", r"\1", f.read_text(encoding="utf-8"))).get("name")] = f
        except ValueError:
            pass
    return out


def main() -> int:
    if len(sys.argv) > 1:
        results = Path(sys.argv[1])
    else:
        runs = sorted((OUT / "bench").glob("*-enemy-strength/results.csv"))
        if not runs:
            sys.exit("no enemy-strength run: python scripts/bench.py --grunts -1 --elites -1 --bosses 0 --label enemy-strength")
        results = runs[-1]
    wins, games = defaultdict(int), defaultdict(int)
    with open(results, encoding="utf-8", newline="") as fh:
        for row in csv.DictReader(fh):
            if row["winner"] in ("enemy", "player", "draw"):
                games[row["enemy"]] += 1
                wins[row["enemy"]] += row["winner"] == "enemy"
    strength = {e: wins[e] / games[e] for e in games if games[e] >= 2}
    ranked = sorted(strength, key=lambda e: strength[e])
    pct = {e: i / max(1, len(ranked) - 1) for i, e in enumerate(ranked)}
    enemies = {e["name"]: e for e in json.loads((COMMON / "enemies.json").read_text(encoding="utf-8"))}
    layout = json.loads((ROOT / "plane" / "world" / "region_layout.json").read_text(encoding="utf-8"))
    files = biome_files()
    print(f"{len(strength)} enemies scored from {results}")
    for region in layout["regions"]:
        rid = region["id"]
        low, high = STEP.get(rid, (0.0, 1.0))
        colours = COLOURS.get(rid, "")
        own = set()
        for b in region["biomes"]:
            data = json.loads(re.sub(r",\s*([\]}])", r"\1", files[b].read_text(encoding="utf-8")))
            own |= set(data.get("enemies", []))
        fits = {n for n, e in enemies.items() if colours and colours in (e.get("colors") or "")}
        candidates = [n for n in own | fits if n in pct and not enemies[n].get("boss")]
        band = [n for n in candidates if low <= pct[n] <= high]
        if len(band) < MIN_ENEMIES:
            middle = (low + high) / 2
            extra = sorted((n for n in candidates if n not in band), key=lambda n: abs(pct[n] - middle))
            band += extra[:MIN_ENEMIES - len(band)]
        band.sort()
        mean = sum(strength[n] for n in band) / len(band)
        for b in region["biomes"]:
            patch = {"_about": f"Generated by scripts/enemy_curve.py: the enemies that roam {region['name']}, "
                               f"strength band {low:.0%}-{high:.0%} of all enemies (measured).",
                     "set": {"enemies": band}}
            (ROOT / "plane" / "world" / "biomes").mkdir(parents=True, exist_ok=True)
            (ROOT / "plane" / "world" / "biomes" / f"{files[b].stem}.patch.json").write_text(
                json.dumps(patch, indent=1, ensure_ascii=False) + "\n", encoding="utf-8", newline="\n")
        print(f"  {region['name']:20} {len(band):3} enemies, mean enemy win rate {mean:.0%} (band {low:.0%}-{high:.0%})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
